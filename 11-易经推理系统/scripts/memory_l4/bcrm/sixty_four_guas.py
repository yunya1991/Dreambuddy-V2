@dataclass
class YaoResult:
    """爻辞结果。"""
    yao_index: int           # 0-5，初爻到上爻
    yao_name: str            # 如"初九"、"六二"
    yao_type: str            # "九"（阳）或"六"（阴）
    is_yang: bool            # 是否阳爻
    is_changing: bool        # 是否动爻
    yao_ci: str              # 爻辞
    yao_xiang: str = ""      # 象曰
    meaning: str = ""        # 含义解释
    market_implication: str = ""  # 市场含义

    def to_dict(self) -> Dict[str, Any]:
        return {
            "yao_index": self.yao_index,
            "yao_name": self.yao_name,
            "yao_type": self.yao_type,
            "is_yang": self.is_yang,
            "is_changing": self.is_changing,
            "yao_ci": self.yao_ci,
            "yao_xiang": self.yao_xiang,
            "meaning": self.meaning,
            "market_implication": self.market_implication,
        }


@dataclass
class HexagramKnowledge:
    """六十四卦知识。"""
    name: str                   # 英文名称
    name_cn: str                # 中文名称
    inner_gua: str              # 内卦（下卦）
    outer_gua: str              # 外卦（上卦）
    gua_ci: str                 # 卦辞
    tuan_zhuan: str             # 彖传
    xiang_zhuan: str            # 象传
    yao_ci: List[str]           # 六爻爻辞
    direction_hint: str         # 方向暗示
    confidence_base: float      # 基础置信度
    market_meaning: str         # 市场含义
    risk_level: str             # 风险等级

    def get_yao_result(self, yao_index: int, is_changing: bool = False) -> YaoResult:
        """获取指定爻的结果。"""
        is_yang = self._get_yao_type(yao_index)
        yao_type = "九" if is_yang else "六"
        yao_name = f"{YAO_POSITIONS[yao_index]}{yao_type}"

        # 兼容 yao_ci 的两种格式：List[str] 和 Dict[int, tuple]
        raw_yao_ci = self.yao_ci[yao_index]
        if isinstance(raw_yao_ci, (tuple, list)):
            # Dict 格式：(yao_name, yao_type, yao_text, xiang_text)
            yao_ci_str = raw_yao_ci[2] if len(raw_yao_ci) > 2 else str(raw_yao_ci)
        else:
            # List 格式：str
            yao_ci_str = str(raw_yao_ci)

        return YaoResult(
            yao_index=yao_index,
            yao_name=yao_name,
            yao_type=yao_type,
            is_yang=is_yang,
            is_changing=is_changing,
            yao_ci=yao_ci_str,
            meaning=self._get_yao_meaning(yao_index),
            market_implication=self._get_yao_market_implication(yao_index),
        )

    def _get_yao_type(self, yao_index: int) -> bool:
        """获取爻的阴阳（从卦象推导）。"""
        inner_bin = GUA_BINARY.get(self.inner_gua, 0)
        outer_bin = GUA_BINARY.get(self.outer_gua, 0)
        full_bin = (outer_bin << 3) | inner_bin
        return bool((full_bin >> yao_index) & 1)

    def _get_yao_meaning(self, yao_index: int) -> str:
        """获取爻位含义。"""
        meanings = [
            "初始阶段，潜藏待时",
            "崭露头角，有所表现",
            "勤勉努力，警惕风险",
            "进退有据，审时度势",
            "鼎盛时期，大展宏图",
            "终极阶段，物极必反",
        ]
        return meanings[yao_index]

    def _get_yao_market_implication(self, yao_index: int) -> str:
        """获取爻的市场含义。"""
        implications = [
            "底部区域，建仓时机",
            "初步上涨，确认趋势",
            "震荡整理，积蓄动能",
            "关键位置，方向选择",
            "加速上涨，趋势明确",
            "顶部区域，注意风险",
        ]
        return implications[yao_index]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "name_cn": self.name_cn,
            "inner_gua": self.inner_gua,
            "outer_gua": self.outer_gua,
            "gua_ci": self.gua_ci,
            "tuan_zhuan": self.tuan_zhuan,
            "xiang_zhuan": self.xiang_zhuan,
            "yao_ci": self.yao_ci,
            "direction_hint": self.direction_hint,
            "confidence_base": self.confidence_base,
            "market_meaning": self.market_meaning,
            "risk_level": self.risk_level,
        }


