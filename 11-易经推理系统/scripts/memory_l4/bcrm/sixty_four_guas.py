def build_hexagram_by_guas(inner_gua: str, outer_gua: str) -> Optional[str]:
    """根据内外卦查找卦名。"""
    for name, data in SIXTY_FOUR_GUAS.items():
        if data["inner_gua"] == inner_gua and data["outer_gua"] == outer_gua:
            return name
    return None


def get_all_hexagram_names() -> List[str]:
    """获取所有六十四卦名称。"""
    return list(SIXTY_FOUR_GUAS.keys())


# 中文名 → 拼音 key 反向映射（P1修复：支持按中文名查找卦象知识）
_HEX_NAME_CN_TO_KEY: Dict[str, str] = {
    v["name_cn"]: k for k, v in SIXTY_FOUR_GUAS.items()
}


def get_hexagram_knowledge(name: str) -> Optional[HexagramKnowledge]:
    """获取指定卦的知识（支持拼音 key 和中文名两种查找方式）。"""
    data = SIXTY_FOUR_GUAS.get(name)
    if not data:
        # 尝试中文名反向查找
        key = _HEX_NAME_CN_TO_KEY.get(name)
        if not key:
            return None
        data = SIXTY_FOUR_GUAS[key]
        name = key
    return HexagramKnowledge(
        name=name,
        name_cn=data["name_cn"],
        inner_gua=data["inner_gua"],
        outer_gua=data["outer_gua"],
        gua_ci=data["gua_ci"],
        tuan_zhuan=data.get("tuan_zhuan", ""),
        xiang_zhuan=data.get("xiang_zhuan", ""),
        yao_ci=data["yao_ci"],
        direction_hint=data["direction_hint"],
        confidence_base=data["confidence_base"],
        market_meaning=data["market_meaning"],
        risk_level=data["risk_level"],
    )
